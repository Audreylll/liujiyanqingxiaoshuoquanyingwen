function renderLibrary(query = "") {
  const q = query.trim().toLowerCase();
  const filtered = q ? allVocab.filter(item => `${item.word} ${item.phonetic} ${item.meaning}`.toLowerCase().includes(q)) : allVocab;
  const visible = filtered.slice(0, 240);
  $("#libraryMeta").textContent = q ? `找到 ${filtered.length} 条结果${filtered.length > 240 ? "，当前显示前 240 条" : ""}` : `共 ${allVocab.length} 条 · 输入关键词可快速定位`;
  $("#libraryResults").innerHTML = visible.map(item => `<article class="library-row"><b>${escapeHtml(item.word)}</b><i>${escapeHtml(item.phonetic)}</i><p>${escapeHtml(item.meaning)}</p></article>`).join("");
}

