function escapeHtml(text = "") {
  return String(text).replace(/[&<>'"]/g, char => ({"&":"&amp;","<":"&lt;",">":"&gt;","'":"&#39;",'"':"&quot;"})[char]);
}

function lookup(word) {
  return vocabMap.get(word.toLowerCase()) || { word, phonetic: "/—/", meaning: "本章语境词义请结合正文理解" };
}

function decorateEnglish(text, words) {
  let result = escapeHtml(text);
  const sorted = [...words].sort((a,b) => b.length - a.length);
  for (const word of sorted) {
    const item = lookup(word);
    const pattern = new RegExp(`\\b(${word.replace(/[.*+?^${}()|[\\]\\]/g, "\\$&")})(s|d|ed|ing)?\\b`, "gi");
    result = result.replace(pattern, match => `<span class="target-word" title="${escapeHtml(item.meaning)}">${match}</span><span class="phonetic-inline">${escapeHtml(item.phonetic)}</span>`);
  }
  return result;
}

function renderChapterList() {
  els.chapterList.innerHTML = chapters.map((chapter, i) => `
    <button class="chapter-item ${i === state.chapter ? "active" : ""} ${state.visited.has(i) ? "visited" : ""}" data-index="${i}">
      <span class="num">${String(i + 1).padStart(2,"0")}</span>
      <span><strong>${chapter.title}</strong><small>${chapter.enTitle}</small></span><i class="dot"></i>
    </button>`).join("");
  els.chapterList.querySelectorAll("button").forEach(button => button.addEventListener("click", () => goToChapter(Number(button.dataset.index))));
}

function renderChapter() {
  const chapter = chapters[state.chapter];
  state.visited.add(state.chapter);
  localStorage.setItem("tide-chapter", state.chapter);
  localStorage.setItem("tide-visited", JSON.stringify([...state.visited]));
  stopSpeech();
  els.kicker.textContent = `CHAPTER ${String(state.chapter + 1).padStart(2,"0")}`;
  els.title.textContent = chapter.title;
  els.subtitle.textContent = chapter.enTitle;
  els.position.textContent = `${String(state.chapter + 1).padStart(2,"0")} / ${chapters.length}`;
  els.storyBody.innerHTML = chapter.paragraphs.map((p, i) => `
    <section class="story-paragraph" data-paragraph="${i}" tabindex="0" title="点击朗读本段">
      <p class="en">${decorateEnglish(p[0], chapter.words)}</p>
      <p class="zh">${escapeHtml(p[1])}</p>
    </section>`).join("");
  els.storyBody.querySelectorAll(".story-paragraph").forEach(row => {
    row.addEventListener("click", () => speakParagraph(Number(row.dataset.paragraph)));
    row.addEventListener("keydown", e => { if (e.key === "Enter") speakParagraph(Number(row.dataset.paragraph)); });
  });
  els.vocabTable.innerHTML = chapter.words.map(word => {
    const item = lookup(word);
    return `<tr><td>${escapeHtml(item.word)}</td><td>${escapeHtml(item.phonetic)}</td><td class="meaning-cell">${escapeHtml(item.meaning)}</td><td><button class="speak-word" data-word="${escapeHtml(item.word)}" aria-label="朗读 ${escapeHtml(item.word)}">♪</button></td></tr>`;
  }).join("");
  els.vocabTable.querySelectorAll(".speak-word").forEach(btn => btn.addEventListener("click", () => speak(btn.dataset.word, "en-US")));
  els.summary.textContent = `共 ${chapter.words.length} 个核心词 · 均来自所附六级词汇表`;
  els.prev.disabled = state.chapter === 0;
  els.next.disabled = state.chapter === chapters.length - 1;
  els.bookmark.textContent = state.bookmarks.has(state.chapter) ? "♥" : "♡";
  els.bookmark.classList.toggle("saved", state.bookmarks.has(state.chapter));
  const percentage = ((state.chapter + 1) / chapters.length) * 100;
  els.progress.style.width = `${percentage}%`;
  els.progressText.textContent = `已读 ${state.visited.size} / ${chapters.length} 章`;
  renderChapterList();
  window.scrollTo({top: 0, behavior: "smooth"});
}

function goToChapter(index) {
  if (index < 0 || index >= chapters.length) return;
  state.chapter = index;
  renderChapter();
  closeSidebar();
}

function speak(text, lang, onend) {
  if (!("speechSynthesis" in window)) return alert("当前浏览器不支持语音朗读，请使用最新版 Chrome、Edge 或 Safari。");
  const utterance = new SpeechSynthesisUtterance(text);
  utterance.lang = lang;
  utterance.rate = lang.startsWith("zh") ? .92 : .88;
  utterance.pitch = 1;
  utterance.onend = () => onend?.();
  speechSynthesis.speak(utterance);
}

function stopSpeech() {
  if ("speechSynthesis" in window) speechSynthesis.cancel();
  state.speaking = false;
  els.play.textContent = "▶";
  els.readChapter.textContent = "▶ 朗读本章";
  document.querySelectorAll(".story-paragraph").forEach(row => row.classList.remove("speaking"));
}

function speakParagraph(index) {
  stopSpeech();
  const chapter = chapters[state.chapter];
  const row = els.storyBody.querySelector(`[data-paragraph="${index}"]`);
  row?.classList.add("speaking");
  if (state.speechMode === "bilingual") {
    speak(chapter.paragraphs[index][0], "en-US", () => speak(chapter.paragraphs[index][1], "zh-CN", () => row?.classList.remove("speaking")));
  } else speak(chapter.paragraphs[index][0], "en-US", () => row?.classList.remove("speaking"));
}

function playChapter() {
  if (state.speaking) return stopSpeech();
  state.speaking = true;
  els.play.textContent = "■";
  els.readChapter.textContent = "■ 停止朗读";
  const chapter = chapters[state.chapter];
  let index = 0;
  const next = () => {
    document.querySelectorAll(".story-paragraph").forEach(row => row.classList.remove("speaking"));
    if (!state.speaking || index >= chapter.paragraphs.length) return stopSpeech();
    const row = els.storyBody.querySelector(`[data-paragraph="${index}"]`);
    row?.classList.add("speaking");
    const [en, zh] = chapter.paragraphs[index++];
    if (state.speechMode === "bilingual") speak(en, "en-US", () => speak(zh, "zh-CN", next));
    else speak(en, "en-US", next);
  };
  next();
}

